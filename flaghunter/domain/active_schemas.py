# --- Public entry point -------------------------------------------------


def register_all_active_schemas(
    registry: InMemorySchemaRegistry,
) -> InMemorySchemaRegistry:
    """Populate ``registry`` with every ACTIVE schema the system knows
    about and return the same instance for chaining.

    The function is idempotent: calling it twice on the same registry
    is safe. It is also the *only* sanctioned way to add an active
    schema; new owners must extend this list (or its successor) so
    that ``active_schemas()`` stays an authoritative answer to the
    C-01 acceptance target.
    """
    for record in (
        _TASK_CANCELLATION_V1,
        _TASK_LIFECYCLE_V1,
        _QUALITY_MANIFEST_V1,
        *_PORT_SCHEMAS,
    ):
        registry.register(record.to_mapping())
    return registry


def known_active_schema_count() -> int:
    """Return how many ACTIVE schemas the canonical catalog contains
    without actually building a registry — useful for tests and for
    the C-01 acceptance guard.
    """
    return 3 + len(_PORT_SCHEMAS)
