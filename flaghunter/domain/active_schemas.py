"""Canonical registration of every active schema in the system.

This is the **single place** that knows about all the schemas the rest
of the codebase reads or writes. It is invoked once at startup (or on
demand from tests) to populate an in-memory
:class:`flaghunter.domain.schema_catalog.InMemorySchemaRegistry` and
nothing else.

Scope (per §13.4 C-01 and §10.3 of the optimization guide):

* Every ACTIVE schema is registered with an explicit owner module.
* Each schema carries a reader/writer compatibility list so that
  ``is_compatible()`` answers can drive a future migration matrix.
* The list is deliberately a **seed**, not the whole truth. New
  schemas must be added here as they are introduced; new owners must
  appear here before they ship.

What is *not* in this file (yet):

* The 600+ ``version=...`` parameters that pepper the codebase. Those
  are application-level option versions, not data schemas; cataloging
  them is out of scope for C-01.
* The ``p2/p3/p4`` working names. Per the masterplan these are
  historical migration sources only and must not appear in the
  canonical registry.

Each registered schema is a ``SchemaRecord`` from
:mod:`flaghunter.domain.schema_catalog`; see that module for the
canonical field list and validation rules.
"""

