// ── interpolation helper ──────────────────────────────────────────
function _interpolate(str, args) {
  return str.replace(/\{(\d+)\}/g, (_, i) => (args[i] !== undefined ? args[i] : `{${i}}`));
}

// ── language state ────────────────────────────────────────────────
window.LANG = localStorage.getItem('fh_lang') || 'zh';

window.setLang = function (lang) {
  window.LANG = lang;
  localStorage.setItem('fh_lang', lang);
  window.dispatchEvent(new CustomEvent('fh:lang', { detail: lang }));
};

window.t = function (key, ...args) {
  const dict = DICT[window.LANG] || DICT.en;
  const val = dict[key] ?? DICT.en[key] ?? key;
  return args.length ? _interpolate(val, args) : val;
};

// React hook that re-renders component on language change
window.useLang = function () {
  const [, forceRender] = React.useState(0);
  React.useEffect(() => {
    const handler = () => forceRender(n => n + 1);
    window.addEventListener('fh:lang', handler);
    return () => window.removeEventListener('fh:lang', handler);
  }, []);
};
